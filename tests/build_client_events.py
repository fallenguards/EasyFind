"""Writes tests/client_events.lua: the events each non-retail client has,
from the client's own generated API docs (Gethe/wow-ui-source, one sparse
clone per branch: Interface/AddOns/Blizzard_APIDocumentationGenerated).

    python tests/build_client_events.py C:/tmp/wus-

reads C:/tmp/wus-<branch> for each branch below.
"""
import os
import re
import subprocess
import sys

# toc game type -> wow-ui-source branch
BRANCHES = {"vanilla": "classic_era", "tbc": "classic_anniversary", "mists": "classic", "camelot": "forever"}
DOCS = "Interface/AddOns/Blizzard_APIDocumentationGenerated"
LITERAL = re.compile(r'LiteralName = "([A-Z0-9_]+)"')


def Events(root):
    names = set()
    folder = os.path.join(root, DOCS)
    for name in os.listdir(folder):
        if name.endswith(".lua"):
            with open(os.path.join(folder, name), encoding="utf-8") as f:
                names.update(LITERAL.findall(f.read()))
    return names


def Wrap(names):
    lines, line = [], ""
    for name in sorted(names):
        if line and len(line) + 1 + len(name) > 100:
            lines.append(line)
            line = name
        else:
            line = (line + " " + name) if line else name
    if line:
        lines.append(line)
    return "\n".join(lines)


def main():
    prefix = sys.argv[1]
    sets, builds = {}, {}
    for kind, branch in BRANCHES.items():
        root = prefix + branch
        sets[kind] = Events(root)
        builds[kind] = subprocess.run(["git", "-C", root, "log", "-1", "--format=%s"], capture_output=True,
                                      text=True).stdout.strip()
    union = set().union(*sets.values())
    out = ["-- Generated by tests/build_client_events.py from each client's API docs:"]
    out += ["-- %s %s" % (kind, builds[kind]) for kind in BRANCHES]
    out.append("-- all: every event any of them has; missing.<type>: what that one lacks.")
    out.append("return {")
    out.append("all = [[\n%s\n]]," % Wrap(union))
    out.append("missing = {")
    for kind in BRANCHES:
        out.append("%s = [[\n%s\n]]," % (kind, Wrap(union - sets[kind])))
    out.append("},")
    out.append("}")
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "client_events.lua")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("%d events; missing: %s" % (len(union), ", ".join("%s %d" % (k, len(union - sets[k])) for k in BRANCHES)))


if __name__ == "__main__":
    main()
